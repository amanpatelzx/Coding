public class main {
    public static void main(String[] args){
        int a = 10;
        int b = a + (int)2.5F;//this is called type casting;
        System.out.println(b);
        float temp = 100.4F;
        float temp1 = temp + 15;//no need of type casting
        
        System.out.println(temp1);
    }
}

